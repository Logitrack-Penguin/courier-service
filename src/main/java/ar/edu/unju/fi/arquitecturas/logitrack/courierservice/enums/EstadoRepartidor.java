package ar.edu.unju.fi.arquitecturas.logitrack.courierservice.enums;

/**
 * Clase de tipo Enumerado correspondiente a los posibles estados que puede tener un repartidor registrado.
 * <ul>
 *     <li>ACTIVO: El repartidor se encuentra trabajando y disponible para realizar la entrega.</li>
 *     <li>INACTIVO: El repartidor no se encuentra trabajando, por lo que no puede realizar la entrega.</li>
 * </ul>
 *
 * @author Logitrack-Penguin
 * @version 1.1.0
 * @since 24-10-2026
 * @see Enum
 */

public enum EstadoRepartidor {
    ACTIVO,
    INACTIVO
}
